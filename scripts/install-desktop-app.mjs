/**
 * Install a double-clickable desktop launcher for JARVIS.
 *
 * One icon that boots the brain and the face and opens the app in Chrome, so
 * after the first `npm start` nobody has to touch a terminal again. Everything
 * is derived from where this file lives — nothing is hardcoded to one machine —
 * so it works from whatever folder the repo was cloned into.
 *
 * It is idempotent and safe to call on every start: if the launcher already
 * exists it does nothing unless `--force` is passed. It installs nothing else,
 * downloads nothing, and never fails the caller — a desktop shortcut is a
 * convenience, not a dependency, so every path degrades to a single warning.
 *
 * Run it directly with `npm run install-app`, or let `npm start` call it once.
 *
 * Platforms: macOS builds a real .app on the Desktop; Windows writes a .cmd and
 * a Desktop shortcut; Linux writes a .desktop entry. macOS is the tested path.
 */

import { spawnSync } from 'node:child_process'
import {
  chmodSync,
  cpSync,
  existsSync,
  mkdirSync,
  mkdtempSync,
  rmSync,
  writeFileSync,
} from 'node:fs'
import { homedir, tmpdir } from 'node:os'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const HERE = dirname(fileURLToPath(import.meta.url))
const REPO = join(HERE, '..') // scripts/ lives directly under the app root
const DESKTOP = join(homedir(), 'Desktop')

/**
 * @param {object} [opts]
 * @param {boolean} [opts.writes]     bake in `--writes` (real actions on)
 * @param {string}  [opts.workspace]  a JARVIS_WORKSPACE folder to run as
 * @param {boolean} [opts.force]      rebuild even if the launcher exists
 * @param {boolean} [opts.quiet]      only speak on error
 * @returns {boolean} whether a launcher now exists
 */
export function installDesktopApp(opts = {}) {
  const writes = opts.writes ?? false
  const workspace = opts.workspace ?? process.env.JARVIS_WORKSPACE ?? ''
  const force = opts.force ?? false
  const say = (m) => {
    if (!opts.quiet) console.log(m)
  }
  const warn = (m) => console.warn(m)

  try {
    if (process.platform === 'darwin') return installMac({ writes, workspace, force, say, warn })
    if (process.platform === 'win32') return installWindows({ writes, workspace, force, say, warn })
    return installLinux({ writes, workspace, force, say, warn })
  } catch (err) {
    warn(`  could not install the desktop app: ${err?.message ?? err}`)
    return false
  }
}

/**
 * The commands the launcher runs, shared across platforms. Built as a POSIX
 * shell body for macOS/Linux; Windows gets its own below. `START` is the npm
 * invocation, `EXPORTS` any environment the run needs.
 */
function shellLauncherBody({ writes, workspace, url = 'http://localhost:5173' }) {
  const start = writes ? 'npm start -- --writes' : 'npm start'
  const exportWorkspace = workspace ? `export JARVIS_WORKSPACE=${shq(workspace)}\n` : ''
  return `#!/bin/sh
# Generated by install-desktop-app.mjs. Boots JARVIS and opens it in Chrome.
# The repo path is baked in below; delete this file and re-run
# \`npm run install-app\` to regenerate it after moving the repo.
set -u
DIR=${shq(REPO)}
URL="${url}"
cd "$DIR" || exit 1
${exportWorkspace}
# Already up? Just open the tab.
if ! curl -s -o /dev/null "http://localhost:8787/health"; then
  : > jarvis-run.log 2>/dev/null || true
  # Fully detached so the servers outlive whatever launched this script.
  nohup ${start} </dev/null >> jarvis-run.log 2>&1 &
  # Wait for the face, up to ~40s.
  i=0
  while [ $i -lt 80 ]; do
    curl -s -o /dev/null "$URL" && break
    sleep 0.5
    i=$((i + 1))
  done
fi
${openCmd()} "$URL" >/dev/null 2>&1 || true
`
}

/** Open a URL in Chrome, falling back to the default browser. */
function openCmd() {
  if (process.platform === 'darwin') {
    return 'open -a "Google Chrome"'
  }
  // Linux: prefer Chrome/Chromium, else xdg-open.
  return 'sh -c \'google-chrome "$0" 2>/dev/null || chromium "$0" 2>/dev/null || xdg-open "$0"\''
}

/** Single-quote a string for POSIX sh. */
function shq(s) {
  return `'${String(s).replace(/'/g, `'\\''`)}'`
}

// --------------------------------------------------------------------- macOS

function installMac({ writes, workspace, force, say, warn }) {
  const app = join(DESKTOP, 'JARVIS.app')
  if (existsSync(app) && !force) {
    say('  desktop app already installed (JARVIS.app on your Desktop).')
    return true
  }

  // A minimal AppleScript app, compiled with the system osacompile, then its
  // payload replaced with our own launcher and icon. do shell script runs the
  // launcher through a login shell so the user's exported keys (a Fish Audio or
  // ElevenLabs key in their profile) are present, backgrounded so osascript
  // returns at once and never reaps the servers.
  const launcher = join(REPO, 'scripts', '.jarvis-desktop-launch.sh')
  writeFileSync(launcher, shellLauncherBody({ writes, workspace }))
  chmodSync(launcher, 0o755)

  const appleScript = `on run
  set launcher to ${JSON.stringify(launcher)}
  display notification "Booting the brain and the face…" with title "J.A.R.V.I.S."
  do shell script "/bin/zsh -lic " & quoted form of launcher & " >/dev/null 2>&1 &"
end run`

  const tmp = mkdtempSync(join(tmpdir(), 'jarvis-app-'))
  const src = join(tmp, 'jarvis.applescript')
  writeFileSync(src, appleScript)

  if (existsSync(app)) rmSync(app, { recursive: true, force: true })
  const r = spawnSync('osacompile', ['-o', app, src], { encoding: 'utf8' })
  if (r.status !== 0) {
    warn(`  osacompile failed: ${(r.stderr || r.error?.message || '').trim()}`)
    rmSync(tmp, { recursive: true, force: true })
    return false
  }

  // Icon: build an .icns from the shipped PNG and drop it in as the app icon.
  const png = join(REPO, 'public', 'jarvis-icon.png')
  if (existsSync(png)) {
    try {
      const iconset = join(tmp, 'jarvis.iconset')
      mkdirSync(iconset, { recursive: true })
      for (const s of [16, 32, 64, 128, 256, 512]) {
        spawnSync('sips', ['-z', String(s), String(s), png, '--out', join(iconset, `icon_${s}x${s}.png`)])
        spawnSync('sips', ['-z', String(s * 2), String(s * 2), png, '--out', join(iconset, `icon_${s}x${s}@2x.png`)])
      }
      const icns = join(tmp, 'jarvis.icns')
      if (spawnSync('iconutil', ['-c', 'icns', iconset, '-o', icns]).status === 0) {
        cpSync(icns, join(app, 'Contents', 'Resources', 'applet.icns'))
        spawnSync('touch', [app]) // nudge Finder to redraw the icon
      }
    } catch {
      /* the default AppleScript icon is fine */
    }
  }

  // Not downloaded, so no quarantine to clear, but be explicit in case a future
  // path copies it in.
  spawnSync('xattr', ['-dr', 'com.apple.quarantine', app])

  rmSync(tmp, { recursive: true, force: true })
  say(`  installed JARVIS.app on your Desktop${writes ? ' (actions enabled)' : ''}. Double-click it any time.`)
  return true
}

// ------------------------------------------------------------------- Windows

function installWindows({ writes, workspace, force, say, warn }) {
  const cmdPath = join(REPO, 'scripts', 'jarvis-desktop-launch.cmd')
  const start = writes ? 'call npm start -- --writes' : 'call npm start'
  const setWorkspace = workspace ? `set "JARVIS_WORKSPACE=${workspace}"\r\n` : ''
  const body =
    `@echo off\r\n` +
    `cd /d "${REPO}"\r\n` +
    setWorkspace +
    `curl -s -o NUL http://localhost:8787/health\r\n` +
    `if errorlevel 1 ( start "" /min cmd /c "${start}" )\r\n` +
    `powershell -NoProfile -Command "for($i=0;$i -lt 80;$i++){try{Invoke-WebRequest -UseBasicParsing http://localhost:5173 -TimeoutSec 1 | Out-Null; break}catch{Start-Sleep -Milliseconds 500}}"\r\n` +
    `start "" chrome "http://localhost:5173" || start "" "http://localhost:5173"\r\n`
  writeFileSync(cmdPath, body)

  const lnk = join(DESKTOP, 'JARVIS.lnk')
  if (existsSync(lnk) && !force) {
    say('  desktop app already installed (JARVIS shortcut).')
    return true
  }
  const png = join(REPO, 'public', 'jarvis-icon.png')
  const ps =
    `$s=(New-Object -ComObject WScript.Shell).CreateShortcut(${psq(lnk)});` +
    `$s.TargetPath=${psq(cmdPath)};$s.WorkingDirectory=${psq(REPO)};` +
    (existsSync(png) ? `$s.IconLocation=${psq(png)};` : '') +
    `$s.Description='Boot JARVIS and open it in Chrome';$s.Save()`
  const r = spawnSync('powershell', ['-NoProfile', '-Command', ps], { encoding: 'utf8' })
  if (r.status !== 0) {
    warn(`  could not create the Desktop shortcut: ${(r.stderr || '').trim()}. The launcher is at scripts/jarvis-desktop-launch.cmd`)
    return false
  }
  say(`  installed the JARVIS shortcut on your Desktop${writes ? ' (actions enabled)' : ''}.`)
  return true
}

/** PowerShell single-quoted literal. */
function psq(s) {
  return `'${String(s).replace(/'/g, "''")}'`
}

// --------------------------------------------------------------------- Linux

function installLinux({ writes, workspace, force, say }) {
  const launcher = join(REPO, 'scripts', '.jarvis-desktop-launch.sh')
  writeFileSync(launcher, shellLauncherBody({ writes, workspace }))
  chmodSync(launcher, 0o755)

  const png = join(REPO, 'public', 'jarvis-icon.png')
  const entry =
    `[Desktop Entry]\n` +
    `Type=Application\n` +
    `Name=JARVIS\n` +
    `Comment=Boot JARVIS and open it in Chrome\n` +
    `Exec=${launcher}\n` +
    (existsSync(png) ? `Icon=${png}\n` : '') +
    `Terminal=false\n` +
    `Categories=Utility;\n`

  const targets = [
    join(homedir(), '.local', 'share', 'applications', 'jarvis.desktop'),
    join(DESKTOP, 'jarvis.desktop'),
  ]
  let any = false
  for (const t of targets) {
    if (existsSync(t) && !force) {
      any = true
      continue
    }
    try {
      mkdirSync(dirname(t), { recursive: true })
      writeFileSync(t, entry)
      chmodSync(t, 0o755)
      any = true
    } catch {
      /* the other target may still succeed */
    }
  }
  say(`  installed a JARVIS launcher${writes ? ' (actions enabled)' : ''}${any ? '' : ' — but no writable location was found'}.`)
  return any
}

// ----------------------------------------------------------------------- CLI

const isCli = process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]
if (isCli) {
  const argv = process.argv.slice(2)
  const wsIndex = argv.indexOf('--workspace')
  installDesktopApp({
    writes: argv.includes('--writes'),
    workspace: wsIndex >= 0 ? argv[wsIndex + 1] : undefined,
    force: argv.includes('--force'),
  })
}
